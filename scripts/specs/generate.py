def _parts(field_id: str) -> list[str]:
    out: list[str] = []
    for segment in field_id.split("."):
        out.extend(part for part in segment.split("_") if part)
    return out


def _camel(field_id: str) -> str:
    parts = _parts(field_id)
    return parts[0].lower() + "".join(p.capitalize() for p in parts[1:])


def _pascal(field_id: str) -> str:
    return "".join(p.capitalize() for p in _parts(field_id))


def _screaming(field_id: str) -> str:
    return "_".join(p.upper() for p in _parts(field_id))


def _wire_precision(proto: dict[str, Any]) -> str:
    vtype = proto["value_type"]
    if vtype == "number":
        return "continuousDouble"
    if vtype == "integer":
        return "discreteInteger"
    if vtype == "boolean":
        return "boolean"
    if vtype == "string":
        return "enumString" if proto.get("allowed_values") else "string"
    if vtype == "object":
        return "object"
    raise ValueError(f"Unsupported value_type: {vtype!r}")


def _is_hdr_relative(field_id: str) -> bool:
    return field_id in ("hdr.relative_temperature", "hdr.relative_tint")


def _is_hdr_rendition(field_id: str) -> bool:
    return field_id in (
        "hdr.peak_limit_ev",
        "hdr.sdr_exposure_ev",
        "hdr.sdr_contrast",
        "hdr.sdr_saturation",
    )


def _fmt_double(value: float | int | None) -> str:
    if value is None:
        return "nil"
    num = float(value)
    if math.isnan(num) or math.isinf(num):
        raise ValueError(f"Non-finite number in spec: {value!r}")
    text = repr(num)
    if "." not in text and "e" not in text and "E" not in text:
        text += ".0"
    return text


def _quote(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _swift_opt_double(value: float | int | None) -> str:
    return "nil" if value is None else _fmt_double(value)


def _kotlin_opt_double(value: float | int | None) -> str:
    return "null" if value is None else _fmt_double(value)


def _csharp_opt_double(value: float | int | None) -> str:
    return "null" if value is None else _fmt_double(value)


def _swift_str_list(items: list[str] | None) -> str:
    if not items:
        return "[]"
    return "[" + ", ".join(_quote(x) for x in items) + "]"


def _kotlin_str_list(items: list[str] | None) -> str:
    if not items:
        return "emptyList()"
    return "listOf(" + ", ".join(_quote(x) for x in items) + ")"


def _csharp_str_array(items: list[str] | None) -> str:
    if not items:
        return "[]"
    return "[" + ", ".join(_quote(x) for x in items) + "]"


def _swift_int_list(items: list[int] | None) -> str:
    if not items:
        return "[]"
    return "[" + ", ".join(str(int(x)) for x in items) + "]"


def _kotlin_int_list(items: list[int] | None) -> str:
    if not items:
        return "emptyList()"
    return "listOf(" + ", ".join(str(int(x)) for x in items) + ")"


def _csharp_int_array(items: list[int] | None) -> str:
    if not items:
        return "[]"
    return "[" + ", ".join(str(int(x)) for x in items) + "]"


def _split_allowed(allowed: list[Any] | None) -> tuple[list[str], list[int]]:
    if not allowed:
        return [], []
    if all(isinstance(v, str) for v in allowed):
        return list(allowed), []
    if all(isinstance(v, int) and not isinstance(v, bool) for v in allowed):
        return [], list(allowed)
    raise ValueError(f"Mixed or unsupported allowed_values: {allowed!r}")


def _load_spec(root: Path) -> dict[str, Any]:
    path = root / SPEC_REL
    if not path.is_file():
        raise ValueError(f"Missing spec file: {SPEC_REL}")
    doc = json.loads(path.read_text(encoding="utf-8"))
    if doc.get("spec_version") != 1 or not isinstance(doc.get("fields"), list):
        raise ValueError(f"Invalid spec structure in {SPEC_REL}")
    seen: set[str] = set()
    for entry in doc["fields"]:
        fid = entry["field_id"]
        if fid in seen:
            raise ValueError(f"Duplicate field_id in {SPEC_REL}: {fid}")
        seen.add(fid)
    return doc


def _sub_fields_map(doc: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {
        f["field_id"]: f["protocol"]["sub_fields"]
        for f in doc["fields"]
        if "sub_fields" in f["protocol"]
    }


def _emit_swift_model(m: dict[str, Any]) -> str:
    default = m["default"]
    if default is None:
        d_expr = ".none"
    elif isinstance(default, bool):
        d_expr = f".boolean({'true' if default else 'false'})"
    elif isinstance(default, (int, float)):
        d_expr = f".number({_fmt_double(default)})"
    elif isinstance(default, str):
        d_expr = f".string({_quote(default)})"
    elif isinstance(default, dict):
        d_expr = ".object"
    else:
        raise ValueError(f"Unsupported model default: {default!r}")

    return (
        "AdjustmentFieldModelSpec("
        f"supported: {'true' if m['supported'] else 'false'}, "
        f"modes: {_swift_str_list(m['modes'])}, "
        f"storageType: {_quote(m['storage_type'])}, "
        f"nullable: {'true' if m['nullable'] else 'false'}, "
        f"min: {_swift_opt_double(m['min'])}, "
        f"max: {_swift_opt_double(m['max'])}, "
        f"defaultValue: {d_expr}, "
        f"scaleFromProtocol: {_quote(m['scale_from_protocol'])}, "
        f"quantization: .{m['quantization']}, "
        f"hdrMin: {_swift_opt_double(m.get('hdr_min'))}, "
        f"hdrMax: {_swift_opt_double(m.get('hdr_max'))}, "
        f"hdrDefaultNumber: {_swift_opt_double(m.get('hdr_default'))}, "
        f"hdrScaleFromProtocol: {_quote(m['hdr_scale_from_protocol']) if m.get('hdr_scale_from_protocol') is not None else 'nil'})"
    )


