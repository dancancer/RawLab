def generated(root: Path) -> dict[str, str]:
    doc = _load_spec(root)
    return {
        SWIFT_REL: _render_swift(doc),
        KOTLIN_REL: _render_kotlin(doc),
        CSHARP_REL: _render_csharp(doc),
    }


def check(root: Path, outputs: dict[str, str]) -> list[str]:
    errors: list[str] = []
    for rel, text in outputs.items():
        path = root / rel
        if not path.is_file() or path.read_bytes() != text.encode("utf-8"):
            errors.append(f"Generated spec differs: {rel}")
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated files without writing")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        outputs = generated(args.root)
        if args.check:
            errors = check(args.root, outputs)
            if errors:
                print("\n".join(errors), file=sys.stderr)
                return 1
            print(f"Checked {len(outputs)} spec files against {SPEC_REL}: byte-identical")
            return 0
        for rel, text in outputs.items():
            path = args.root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
        print(f"Generated {len(outputs)} spec files from {SPEC_REL}")
        return 0
    except (ValueError, KeyError, TypeError, OSError, json.JSONDecodeError) as exc:
        print(f"Spec generation error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
