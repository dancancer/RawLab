def _emit_csharp_model(m: dict[str, Any]) -> str:
    default = m["default"]
    if default is None:
        d_expr = "AdjustmentModelDefault.None"
    elif isinstance(default, bool):
        d_expr = f"AdjustmentModelDefault.FromBoolean({'true' if default else 'false'})"
    elif isinstance(default, (int, float)):
        d_expr = f"AdjustmentModelDefault.FromNumber({_fmt_double(default)})"
    elif isinstance(default, str):
        d_expr = f"AdjustmentModelDefault.FromString({_quote(default)})"
    elif isinstance(default, dict):
        d_expr = "AdjustmentModelDefault.Object"
    else:
        raise ValueError(f"Unsupported model default: {default!r}")

    q_name = m["quantization"].capitalize()
    return (
        "new AdjustmentFieldModelSpec("
        f"{'true' if m['supported'] else 'false'}, "
        f"{_csharp_str_array(m['modes'])}, "
        f"{_quote(m['storage_type'])}, "
        f"{'true' if m['nullable'] else 'false'}, "
        f"{_csharp_opt_double(m['min'])}, "
        f"{_csharp_opt_double(m['max'])}, "
        f"{d_expr}, "
        f"{_quote(m['scale_from_protocol'])}, "
        f"AdjustmentModelQuantization.{q_name}, "
        f"{_csharp_opt_double(m.get('hdr_min'))}, "
        f"{_csharp_opt_double(m.get('hdr_max'))}, "
        f"{_csharp_opt_double(m.get('hdr_default'))}, "
        f"{_quote(m['hdr_scale_from_protocol']) if m.get('hdr_scale_from_protocol') is not None else 'null'})"
    )


