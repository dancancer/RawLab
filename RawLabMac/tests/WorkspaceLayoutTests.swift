import Foundation

@main struct WorkspaceLayoutTests {
    static func main() {
        var layout = MacWorkspaceLayout()
        precondition(layout.mode == .editing)
        precondition(layout.libraryPresentation(width: 1180) == .pinned)
        precondition(layout.libraryPresentation(width: 1179) == .hidden)
        precondition(layout.showsInspector(hasPhoto: true) && !layout.showsInspector(hasPhoto: false))
        precondition(MacWorkspaceLayout.libraryWidth(1000) == 288)
        precondition(MacWorkspaceLayout.libraryWidth(150) == 200)
        precondition(MacWorkspaceLayout.inspectorWidth(350, windowWidth: 950) == 280)
        precondition(MacWorkspaceLayout.inspectorWidth(350, windowWidth: 1440) == 350)
        precondition(MacWorkspaceLayout.inspectorWidth(500, windowWidth: 1440) == 360)
        precondition(MacWorkspaceLayout.inspectorWidth(200, windowWidth: 1440) == 280)

        layout.toggleLibrary(width: 950)
        precondition(layout.libraryPresentation(width: 950) == .drawer)
        layout.windowResized(from: 950, to: 1180)
        precondition(layout.libraryPresentation(width: 1180) == .pinned)
        layout.windowResized(from: 1180, to: 950)
        precondition(layout.libraryPresentation(width: 950) == .hidden)
        layout.toggleLibrary(width: 950)
        precondition(layout.dismissTransient())
        precondition(layout.libraryPresentation(width: 950) == .hidden)
        precondition(!layout.dismissTransient())
        layout.toggleLibrary(width: 1440)
        layout.toggleInspector()
        precondition(layout.libraryPresentation(width: 1440) == .hidden && !layout.showsInspector(hasPhoto: true))

        layout.setMode(.selection)
        layout.toggleLibrary(width: 950)
        precondition(layout.libraryPresentation(width: 950) == .drawer && !layout.showsInspector(hasPhoto: true))
        layout.setMode(.preview)
        precondition(layout.libraryPresentation(width: 950) == .hidden && !layout.showsInspector(hasPhoto: true))
        precondition(layout.dismissTransient() && layout.mode == .selection)
        precondition(layout.libraryPresentation(width: 950) == .drawer)
        layout.setMode(.preview)
        layout.windowResized(from: 950, to: 1200)
        layout.windowResized(from: 1200, to: 950)
        precondition(layout.dismissTransient() && layout.mode == .selection)
        precondition(layout.libraryPresentation(width: 950) == .hidden)
        layout.photoOpened()
        precondition(layout.mode == .editing && !layout.showsInspector(hasPhoto: true))
        precondition(layout.libraryPresentation(width: 1440) == .hidden)
        layout.showInspector()
        layout.toggleLibrary(width: 1440)
        layout.setMode(.preview)
        layout.photoOpened()
        precondition(layout.mode == .preview)
        precondition(layout.dismissTransient() && layout.mode == .editing)
        precondition(layout.libraryPresentation(width: 1440) == .pinned && layout.showsInspector(hasPhoto: true))
        print("PASS Mac workspace widths, docked/overlay browser, edit/selection/preview restoration")
    }
}
