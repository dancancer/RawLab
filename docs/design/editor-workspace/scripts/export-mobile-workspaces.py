"""Export standalone and unified review surfaces from maintained source assets.

Usage: python3 export-mobile-workspaces.py /absolute/output/directory
Only design assets are read; no native application or camera is used.
"""
import base64
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
SOURCES = (
    ("editor-workspaces", ROOT / "docs/design/editor-workspace/mobile-workspaces"),
    ("camera-workspaces", ROOT / "docs/design/camera-transfer/prototype/workspaces"),
)


def export(destination: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    parts = []
    for name, source in SOURCES:
        html = source.with_suffix(".html").read_text()
        body = re.search(r'(<div id="rl-.*?</div>)\s*<script src=', html, re.S)
        if body is None:
            raise ValueError(f"Missing review root: {source}")
        css = source.with_suffix(".css").read_text()
        script = source.with_suffix(".js").read_text()
        for photo in set(re.findall(r"[.\w/-]+/landscape-\d\.jpg", script)):
            image = (source.parent / photo).read_bytes()
            script = script.replace(photo, "data:image/jpeg;base64," + base64.b64encode(image).decode())
        fragment = "<style>\n" + css + "</style>\n" + body.group(1) + "\n<script>\n" + script + "</script>\n"
        if len(fragment.encode()) >= 1_000_000:
            raise ValueError(f"Review fragment exceeds size limit: {name}")
        target = destination / (name + ".html")
        target.write_text(fragment)
        print(f"{name}: {len(fragment.encode())} bytes")
        parts.append((body.group(1), css, script))

    editor = ROOT / "docs/design/editor-workspace"
    navigation = ('<nav class="review-switch" aria-label="移动原型范围">'
                  '<button data-review-view="editor" aria-pressed="false">编辑</button>'
                  '<button data-review-view="camera" aria-pressed="true">相机入口</button>'
                  '<button data-review-view="import" aria-pressed="false">从相机导入</button>'
                  '<button data-review-view="tether" aria-pressed="false">联机拍摄</button></nav>')
    bodies = parts[0][0].replace('id="rl-editor-review"', 'id="rl-editor-review" hidden') + parts[1][0]
    root = '<div id="rl-mobile-review">' + navigation + bodies + '</div>'
    css = (editor / "mobile-review.css").read_text() + parts[0][1] + parts[1][1]
    script = parts[0][2] + parts[1][2] + (editor / "mobile-review.js").read_text()
    fragment = '<style>\n' + css + '</style>\n' + root + '\n<script>\n' + script + '</script>\n'
    if len(fragment.encode()) >= 1_000_000:
        raise ValueError("Unified review fragment exceeds size limit")
    (destination / "mobile-review.html").write_text(fragment)

    local_root = root.replace('id="rl-camera-review"', 'id="rl-camera-review" data-asset-base="../camera-transfer/prototype/"')
    document = ('<!doctype html>\n<html lang="zh-CN">\n<meta charset="utf-8">'
                '<meta name="viewport" content="width=device-width,initial-scale=1">'
                '<title>RawLab 移动编辑与相机 · 待审核</title>'
                '<link rel="stylesheet" href="mobile-review.css">'
                '<link rel="stylesheet" href="mobile-workspaces.css">'
                '<link rel="stylesheet" href="../camera-transfer/prototype/workspaces.css">'
                '<style>body{margin:0;padding:24px 16px;background:#eeeeec;--foreground:#242426;--background:#fafafa;--border:#99999d;--primary:#28282b;--primary-foreground:#fff}'
                '.sr-only{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0,0,0,0)}'
                '.viz-dotted-background{background-image:radial-gradient(#9995 .7px,transparent .7px);background-size:14px 14px}</style>\n'
                '<!-- Generated by scripts/export-mobile-workspaces.py; edit the source workspaces. -->\n'
                + local_root + '\n<script src="shared/mobile-review-icons.js"></script>'
                '<script src="mobile-workspaces.js"></script>'
                '<script src="../camera-transfer/prototype/workspaces.js"></script>'
                '<script src="mobile-review.js"></script>\n</html>\n')
    (editor / "mobile-review.html").write_text(document)
    print(f"mobile-review: {len(fragment.encode())} bytes")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("Usage: export-mobile-workspaces.py /absolute/output/directory")
    export(Path(sys.argv[1]).resolve())
